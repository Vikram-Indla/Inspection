-- ---------------------------------------------------------------------------
-- 4 · Previous-inspection comparison read (M04-136 / M04-137):
--     an inspector assigned to any visit of a factory may READ that factory's
--     APPROVED prior inspections (answers + evidence) for field comparison.
--     SECURITY DEFINER helper mirrors is_assigned_inspector (0002) to avoid
--     nested-RLS recursion inside policy expressions.
-- ---------------------------------------------------------------------------
create or replace function inspects_same_factory(v uuid) returns boolean
language sql stable security definer set search_path = public as
$$ select exists (
     select 1
     from visits target
     join visits mine on mine.factory_id = target.factory_id
     join assignments a on a.visit_id = mine.id
     where target.id = v and a.inspector_id = auth.uid()) $$;

do $$ begin
  create policy inspections_read_prior_approved on inspections for select using (
    status = 'approved' and inspects_same_factory(visit_id));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy responses_read_prior_approved on checklist_responses for select using (
    exists (select 1 from inspections i where i.id = inspection_id
            and i.status = 'approved' and inspects_same_factory(i.visit_id)));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy evidence_read_prior_approved on evidence for select using (
    exists (select 1 from inspections i where i.id = inspection_id
            and i.status = 'approved' and inspects_same_factory(i.visit_id)));
exception when duplicate_object then null; end $$;

