-- ---------------------------------------------------------------------------
-- 2 · Inspection numbering (M04-209) — 'INS-YYYY-000123' from a DB sequence.
--     Stamped at inspection start: the startup flow calls next_inspection_no()
--     and inserts the value; the BEFORE INSERT trigger backstops any writer
--     that skips the RPC so no inspection is ever unnumbered.
-- ---------------------------------------------------------------------------
alter table inspections enable row level security;              -- idempotent re-assert
create sequence if not exists inspection_no_seq;
alter table inspections add column if not exists inspection_no text unique;
comment on column inspections.inspection_no is 'Official inspection number INS-YYYY-NNNNNN (M04-209), generated by next_inspection_no() at start.';

create or replace function next_inspection_no() returns text
language sql security definer set search_path = public as
$$ select 'INS-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('inspection_no_seq')::text, 6, '0') $$;
revoke all on function next_inspection_no() from public;
grant execute on function next_inspection_no() to authenticated;

create or replace function stamp_inspection_no() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.inspection_no is null then new.inspection_no := next_inspection_no(); end if;
  return new;
end $$;
drop trigger if exists trg_inspection_no on inspections;
create trigger trg_inspection_no before insert on inspections
  for each row execute function stamp_inspection_no();

