// Governed KPI registry — traceable definition for EVERY metric in
// SAQEEL_Dashboard_KPI_Admin_Configuration_Matrix.xlsx and the CODEX 01 spec
// (12 strategic + 9 operational + 7 inspector = 28 metrics).
//
// This registry is the code-side mirror of the seeded rows in
// public.mvp3_kpi_definitions (see migration
// 20260721010000_dashboard_kpi_admin_foundation.sql). The formula text and
// metricId are IMMUTABLE to ordinary admins — only tested code releases change
// them. Admins may only edit approved parameters via the Dashboard
// Configuration engine.
//
// `implementation` records what the shared projection can deliver TODAY against
// the live schema. Where a required source field/table or governance decision
// is missing, the metric is honestly marked and the projection emits an
// unavailable/not_configured/decision_required SharedMetric rather than a
// fabricated value.

import type { MetricCategory, MetricImplementationStatus, MetricUnit } from "./contract";

export type KpiDefinition = {
  metricId: string;
  category: MetricCategory;
  /** Short stable key, mirrors mvp3_kpi_definitions.metric_key. */
  metricKey: string;
  titleEn: string;
  titleAr: string | null;
  unit: MetricUnit;
  formulaVersion: string;
  /** Human-readable governed formula (immutable to admins). */
  formula: string;
  /** Denominator rule, or "n/a" when the metric is a plain count/category. */
  denominatorRule: string;
  /** Default drill route; filters resolved at projection time. */
  drillRoute: string | null;
  /** Owning admin role for policy parameters (roles.role_key). */
  ownerRole: string;
  implementation: MetricImplementationStatus;
  /** Why not fully implemented, or the governance note when implemented. */
  note: string;
  /** Open decision / stop-line id when relevant. */
  decisionRef: string | null;
  /** Matrix requirement id for traceability. */
  matrixRef: string;
};

