export const KPI_BY_ID: ReadonlyMap<string, KpiDefinition> = new Map(
  KPI_DEFINITIONS.map((d) => [d.metricId, d]),
);

export function kpiDefinition(metricId: string): KpiDefinition | undefined {
  return KPI_BY_ID.get(metricId);
}

export function kpisByCategory(category: MetricCategory): KpiDefinition[] {
  return KPI_DEFINITIONS.filter((d) => d.category === category);
}
